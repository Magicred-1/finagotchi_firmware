// Build with the LVGL qrcodegen source, then run with the output header path:
// cc tools/make_qr_assets.c .pio/libdeps/pcb-v1/lvgl/src/libs/qrcode/qrcodegen.c \
//   -DLV_CONF_INCLUDE_SIMPLE=1 -DLV_USE_QRCODE=1 -Isrc \
//   -I.pio/libdeps/pcb-v1/lvgl/src/libs/qrcode \
//   -I.pio/libdeps/pcb-v1/lvgl/include -o /tmp/make_qr_assets
// /tmp/make_qr_assets src/ui/qr_assets.h

#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include "qrcodegen.h"

#define SIZE 144
#define SCALE 3
#define QUIET 4
#define LIGHT 0xF7DF
#define DARK 0x094B

static bool write_asset(FILE* out, const char* name, const char* url) {
  uint8_t temp[qrcodegen_BUFFER_LEN_MAX];
  uint8_t qr[qrcodegen_BUFFER_LEN_MAX];
  if (!qrcodegen_encodeText(url, temp, qr, qrcodegen_Ecc_MEDIUM,
                            qrcodegen_VERSION_MIN, qrcodegen_VERSION_MAX,
                            qrcodegen_Mask_AUTO, true)) return false;

  int modules = qrcodegen_getSize(qr);
  int used = (modules + QUIET * 2) * SCALE;
  int margin = (SIZE - used) / 2;
  uint16_t pixels[SIZE * SIZE];
  for (int i = 0; i < SIZE * SIZE; i++) pixels[i] = LIGHT;

  for (int y = 0; y < used; y++) {
    for (int x = 0; x < used; x++) {
      int qx = x / SCALE - QUIET;
      int qy = y / SCALE - QUIET;
      if (qrcodegen_getModule(qr, qx, qy))
        pixels[(margin + y) * SIZE + margin + x] = DARK;
    }
  }

  fprintf(out, "const uint16_t %s_data[%d] PROGMEM = {\n", name, SIZE * SIZE);
  for (int i = 0; i < SIZE * SIZE; i++) {
    if (i % 12 == 0) fputs("  ", out);
    fprintf(out, "0x%04X,%s", pixels[i], i % 12 == 11 ? "\n" : " ");
  }
  fputs("};\n\n", out);
  fprintf(out,
          "const lv_image_dsc_t %s = {\n"
          "  { LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565, 0, %d, %d, %d, 0 },\n"
          "  sizeof(%s_data),\n"
          "  reinterpret_cast<const uint8_t*>(%s_data),\n"
          "};\n\n",
          name, SIZE, SIZE, SIZE * 2, name, name);
  return true;
}

int main(int argc, char** argv) {
  if (argc != 2) {
    fprintf(stderr, "usage: %s src/ui/qr_assets.h\n", argv[0]);
    return 2;
  }
  FILE* out = fopen(argv[1], "w");
  if (!out) return 1;
  fputs("// Auto-generated by tools/make_qr_assets.c; do not edit.\n"
        "#pragma once\n"
        "#include <lvgl.h>\n\n", out);
  bool ok = write_asset(out, "qr_ios", "https://finagotchi.app/ios") &&
            write_asset(out, "qr_android", "https://finagotchi.app/android");
  fclose(out);
  return ok ? 0 : 1;
}
