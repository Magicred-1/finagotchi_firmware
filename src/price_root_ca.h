// price_root_ca.h — trust anchors for the anonymous price feeds.
//
// The feeds carry no credentials, but they DO drive what the device shows
// as portfolio value: with setInsecure() anyone on the Wi-Fi path (rogue
// AP, ARP spoof, captive portal) could feed arbitrary prices. Each host is
// now validated against its issuing roots (checked 2026-10 with openssl
// s_client -CAfile):
//   api.jup.ag      leaf <- Amazon RSA 2048 M01 <- Amazon Root CA 1
//                   (Starfield Services G2 cross-sign kept as a fallback)
//   api.xstocks.fi  leaf <- Google Trust Services WE1 <- GTS Root R4
//                   (GTS Root R1 + GlobalSign Root CA kept for rotation)
// All roots are valid until 2028-2038. If a provider moves CA, the fetch
// fails closed (cached prices stay on screen) — update the PEMs here.

